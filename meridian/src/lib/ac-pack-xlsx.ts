import ExcelJS from "exceljs";
import type { PackSnapshot } from "@/lib/ac-pack";
import { BANDS } from "@/lib/erm";

type PackMeta = { status: string; releasedAt: string | null; snapshotHash: string; periodFrom: string; periodTo: string };

/** Builds the Excel pack from the stored snapshot only. */
export async function buildPackWorkbook(pack: PackMeta, s: PackSnapshot) {
  const released = pack.status === "Released";
  const wb = new ExcelJS.Workbook();
  wb.creator = "Meridian Assurance Workbench";
  const banner = released ? `RELEASED ${pack.releasedAt?.slice(0, 10)} · sha256 ${pack.snapshotHash}` : "DRAFT — not issued";
  const sheet = (name: string, headers: string[], rows: (string | number)[][]) => {
    const ws = wb.addWorksheet(name);
    ws.addRow([banner]).font = { bold: true, color: { argb: released ? "FF14583D" : "FFA02828" } };
    ws.addRow([`Period ${s.period.from} to ${s.period.to}. Status as at ${s.asOf}.`]);
    ws.addRow([]);
    ws.addRow(headers).font = { bold: true };
    rows.forEach((r) => ws.addRow(r));
    ws.columns.forEach((c) => { c.width = 26; });
    return ws;
  };
  sheet("Summary", ["Item", "Value"], [
    ["Pack status", released ? "Released" : "DRAFT — not issued"], ["Generated by", s.generatedBy], ["Snapshot sha256", pack.snapshotHash],
    ["Open findings", s.findings.total], ...BANDS.map((b): [string, number] => [`Open findings: ${b}`, s.findings.byBand[b]]),
    ["Overdue actions", s.overdueActions.length], ["Risks", s.erm.total], ["Residual not assessed", s.erm.residualNotAssessed], ["Risks with no linked control", s.erm.withoutControl],
    ...(s.restricted ? [["Restricted engagements", s.restricted.note] as [string, string]] : []),
  ]);
  sheet("Plan progress", ["Quarter", "Items", "Planned", "In progress", "Completed", "Deferred", "Cancelled"], s.plan ? Object.entries(s.plan.byQuarter).map(([q, r]) => [q, r.total, r.Planned, r["In progress"], r.Completed, r.Deferred, r.Cancelled]) : [["No approved plan found", "", "", "", "", "", ""]]);
  if (s.plan?.deferredCancelled.length) sheet("Deferred cancelled", ["Status", "Item", "Quarter", "Reason"], s.plan.deferredCancelled.map((d) => [d.status, d.title, d.quarter, d.reason]));
  sheet("Issued reports", ["Code", "Title", "Opinion", "Issued"], s.issuedReports.map((r) => [r.code, r.title, r.opinion, r.issuedAt]));
  sheet("Open findings", ["Age", ...BANDS], s.findings.buckets.map((b) => [b, ...BANDS.map((x) => s.findings.ageing[b][x])]));
  sheet("Overdue actions", ["Finding", "Engagement", "Action", "Owner", "Owner role", "Due", "Days overdue", "Band", "Follow-up"], s.overdueActions.map((a) => [a.findingCode, a.engagementCode, a.agreedAction, a.ownerName, a.ownerRole, a.due, a.daysOverdue, a.band, a.cadence]));
  sheet("ERM", ["Top residual risk", "Entity", "Inherent", "Residual", "Band"], s.erm.top.map((r) => [r.title, r.entity, r.inherent ?? "", r.residual, r.band]));
  sheet("Kaizen", ["Lesson", "Area", "Proposed"], s.lessons.map((l) => [l.title, l.area, l.created]));
  sheet("Limitations", ["Limitation"], s.limitations.map((l) => [l]));
  return wb.xlsx.writeBuffer();
}
